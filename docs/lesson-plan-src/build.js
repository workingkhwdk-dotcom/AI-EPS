function flowTable() {
  let h = "";
  for (const st of stages) {
    st.blocks.forEach((b, i) => {
      const n = st.blocks.length;
      h += `<tr class="${i ? "cont" : "first"} ${i < n - 1 ? "nl" : "last"}">` +
        (i ? "" : `<td class="stg" rowspan="${n}">${st.name}</td>`) + `<td class="act">${b.l}</td>` +
        (i ? "" : `<td class="tm" rowspan="${n}">${st.time}</td>`) + `<td class="aux">${b.r}</td></tr>`;
    });
  }
  return h;
}

