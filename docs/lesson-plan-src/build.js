function keepWords(src) {
  const WJ = "\u2060";
  let skip = 0;
  return src.split(/(<[^>]+>)/).map((part) => {
    if (part.startsWith("<")) { if (/^<(pre|style)\b/i.test(part)) skip++; else if (/^<\/(pre|style)>/i.test(part)) skip--; return part; }
    if (skip > 0) return part;
    return part
      .replace(/([)\]’”])(?=[^\s<)\]’”,.·/])/g, `$1${WJ}`)
      .replace(/(?<=[^\s(\[‘“])([(\[‘“])/g, `${WJ}$1`)
      .replace(/(?<=\S)([·~])(?=\S)/g, `${WJ}$1${WJ}`)
      .replace(/([①-⑳]) (?=\S)/g, "$1\u00a0"); // ① 누구인지: 번호와 다음 낱말을 한 줄에
  }).join("");
}
