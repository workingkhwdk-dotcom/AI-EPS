// 사건의 범위와 공통 범위를 합친다
function scopeOf(ev) {
  const sc = ev.scope;
  return {
    event: sc.event, time: sc.time, place: sc.place,
    allowedTopics: [...sc.allowedTopics, ...CHARTER.common.allowedTopics],
    outOfScope: [...sc.outOfScope, ...CHARTER.common.outOfScope],
  };
}

// 생성용(페르소나 프롬프트에 삽입)
function charterText(ev) {
  const sc = scopeOf(ev);
  return [
    "[상위 규범] 너는 아래 규범을 가진 상위 감독 아래에서만 말한다.",
    `- 사건: ${sc.event}. 시간: ${sc.time} 장소: ${sc.place}.`,
    `- 허용 주제: ${sc.allowedTopics.join(" / ")}`,
    `- 범위 밖: ${sc.outOfScope.join(" / ")}`,
    ...CHARTER.rules.map((r, i) => `${i + 1}. ${r}`),
  ].join("\n");
}

// 개인으로 등장하는 인물(사건의 당사자·주민)은 신상 질문에 설정대로 답하고, 단체·기관 소속 인물(시민사회, 제도)은 신상을 말할 필요가 없다.
// 어느 축이 개인인지는 사건마다 다르다(EVENT.personalAxes). 사건을 알 수 없는 인물은 기본값을 쓴다.
const PERSONAL_AXES = ["당사자", "도민"];
const isPersonal = (persona) => {
  const ev = require("./case").EVENTS[persona?.events?.[0]];
  return (ev?.personalAxes || PERSONAL_AXES).includes(persona?.axis);
};

module.exports = { CHARTER, scopeOf, charterText, PERSONAL_AXES, isPersonal };
