const beliefStyle = (level, subtle) => BELIEF_STYLE[subtle ? "subtle" : isMid(level) ? "middle" : "high"];

// 1단계: 학생이 메신저로 인터뷰하는 인물. 완전히 그 사람이 되어, 자기 경험과 생각을 자연스럽게 말한다.
