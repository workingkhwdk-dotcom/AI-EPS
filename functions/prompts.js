// 학교급과 심화 활동에 맞춘 유형 목록. 중학교는 원인 갈래가 2개(public/app.js 의 CAUSE_LEVELS_MID)이고,
// 원인 잇기(causeMap)를 하면 원인끼리의 연결을 보는 유형이 더해진다.
function coachKinds(focus, { level = "high", causeMap = false } = {}) {
  const k = { ...COACH_KINDS[focus] };
  if (focus !== "cause") return k;
  if (isMid(level)) k["한 군데만 봄"] = "원인이 모두 사람들의 마음이나 선택에만(또는 규칙에만) 몰려 있다. → 아직 살펴보지 않은 쪽(사람들의 생각·선택 / 사회의 규칙·분위기)을 보게 묻는다.";
  if (causeMap) {
    const good = k["잘 짜임"];
    delete k["잘 짜임"];
    k["따로 놂"] = "원인을 늘어놓기만 하고 서로 어떻게 이어지는지는 보지 않았다(또는 이은 것이 억지스럽다). → 원인 하나가 다른 원인을 부르거나 키우지는 않는지 묻는다.";
    k["잘 짜임"] = good.replace("→ 이 가운데", "→ 이 가운데 무엇이 사라지면 다른 원인도 함께 줄어들지, 또는");
  }
  return k;
}
