  "문장은 짧게 쓰고, 어려운 한자어나 제도·통계 용어(예: 인도적 체류, 헌법불합치, 합계출산율)는 쉬운 말로 풀거나 바로 뒤에 괄호로 짧게 뜻을 붙인다. " + SAFETY;
const common = (level) => (isMid(level) ? COMMON_MID : COMMON);

// 인물의 틀릴 수 있는 믿음을 어떻게 말할지. 학교급과 심화 활동(beliefs)에 따라 학생이 찾아내기 쉬운 정도가 달라진다.
//  - 고등학교 기본: 자신 있게 말하고 반대 근거에 흔들릴 수 있다(예전과 같다).
//  - 중학교: 어디서 들었는지 드러나게 한 문장으로 분명하게 말해 확인하기 쉽다. 반대 근거를 보이면 솔직하게 받아들인다.
